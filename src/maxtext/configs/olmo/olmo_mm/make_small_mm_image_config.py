"""Write the image-only OLMo-core mixture config for the Small multimodal SFT (OLMO_MM_TEXT_NPZ_DIR mode).

Starts from the Tiny H231 config (``olmo35_mmsft_4n_emo256k_config.json``: stage-2 v1 sources, loader settings), drops
the text source, and sets each image source's target loss mass from OLMo-core #942's stage-2 v1 dose rule at the
requested image-token dose (``olmo35_sft_mm_v1.expected_examples`` x ``MEAN_LOSS_WEIGHTS``, anchors at fixed tokens),
renormalized over the image sources. Also prints the schedule numbers (image rows, steps, loss share) for a text
stream of ``--text-rows`` rows with ``--text-supervised`` supervised tokens.

Usage: python make_small_mm_image_config.py --dose 1.55e9 --rows 16 --text-rows 129216 \
         --text-supervised 7575051137 --seed 34521 --out olmo35_small_mmsft_images_s2v1_1p55b.json
Needs OLMo-core #942 importable (``olmo_core.data.multimodal.mixtures.olmo35_sft_mm_v1``).
"""

import argparse
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
TINY = os.path.join(HERE, "olmo35_mmsft_4n_emo256k_config.json")
TEXT_SOURCE = "text_sft"


def main():
  ap = argparse.ArgumentParser()
  ap.add_argument("--dose", type=float, required=True, help="image-data tokens (packed positions) over the run")
  ap.add_argument("--rows", type=int, default=16, help="trained rows per step")
  ap.add_argument("--seq", type=int, default=65536)
  ap.add_argument("--text-rows", type=int, required=True, help="text rows the run trains (prepacked stream)")
  ap.add_argument("--text-supervised", type=int, required=True, help="their supervised tokens (loss mass)")
  ap.add_argument("--pack-fill", type=float, default=0.95)
  ap.add_argument("--seed", type=int, default=34521)
  ap.add_argument("--work-dir", default="/tmp/olmo_mm_work")
  ap.add_argument("--out", required=True)
  args = ap.parse_args()

  from olmo_core.data.multimodal.mixtures import olmo35_sft_mm_v1 as v1  # pylint: disable=import-outside-toplevel

  raw = json.load(open(TINY))
  ds = raw["dataset"]
  examples = v1.expected_examples(args.dose)
  names = [n for n in ds["sources"] if n != TEXT_SOURCE]
  if set(names) != set(examples):
    raise SystemExit(f"source mismatch: config {sorted(set(names) ^ set(examples))}")
  mass = {n: examples[n] * v1.MEAN_LOSS_WEIGHTS[n] for n in names}
  total_mass = sum(mass.values())
  ds["sources"] = {n: ds["sources"][n] for n in names}
  ds["target_loss_mass"] = {n: mass[n] / total_mass for n in names}
  ds["mean_loss_weight"] = {n: ds["mean_loss_weight"][n] for n in names}
  dl = raw["data_loader"]
  dl["global_batch_size"] = args.rows * args.seq
  dl["seed"] = args.seed
  dl["work_dir"] = args.work_dir

  image_rows = args.dose / (args.seq * args.pack_fill)
  image_rows = int(math.ceil(image_rows / args.rows) * args.rows)  # whole steps' worth, so steps are integral
  # U = ceil((T + I) / R) and image slots R x U - T, so the loader's check (steps x rows - image rows = text rows)
  # holds when T is not a multiple of R; the extra slots (< R) are image rows past the dose.
  steps = -(-(args.text_rows + image_rows) // args.rows)
  dose_rows, image_rows = image_rows, steps * args.rows - args.text_rows
  share = total_mass / (total_mass + args.text_supervised)
  out = {
      "_note": (
          "Image-only stage-2 v1 mixture for OLMO_MM_TEXT_NPZ_DIR runs (text from a prepacked stream). Generated by "
          "make_small_mm_image_config.py from olmo35_mmsft_4n_emo256k_config.json; only dataset, data_loader and "
          "train_module.padding_input_token_id are read."
      ),
      "schedule": {
          "image_dose_tokens": args.dose,
          "image_examples": sum(examples.values()),
          "image_loss_mass": total_mass,
          "text_rows": args.text_rows,
          "text_supervised_tokens": args.text_supervised,
          "image_dose_rows": dose_rows,
          "image_rows": image_rows,
          "steps_text_matched": steps,
          "image_loss_share": share,
          "OLMO_MM_IMAGE_ROWS": image_rows,
          "OLMO_MM_SCHEDULE_STEPS": steps,
          "OLMO_MM_TEXT_ROWS": args.text_rows,
      },
      "dataset": ds,
      "data_loader": dl,
      "train_module": {"padding_input_token_id": raw["train_module"]["padding_input_token_id"]},
  }
  with open(args.out, "w") as f:
    json.dump(out, f, indent=1)
  print(json.dumps(out["schedule"], indent=1))


if __name__ == "__main__":
  main()
